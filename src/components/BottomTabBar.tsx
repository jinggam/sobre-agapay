export default function BottomTabBar({ activeTab, onTabChange }: BottomTabBarProps) {
  return (
    <nav
      className="bg-card border-t border-border flex items-stretch"
      style={{ paddingBottom: 'env(safe-area-inset-bottom)' }}
      aria-label="Pangunahing nabigasyon"
    >
      {TABS.map((tab) => {
        const isActive = tab.id === activeTab
        return (
          <button
            key={tab.id}
            onClick={() => onTabChange(tab.id)}
            className={[
              'flex-1 flex flex-col items-center justify-center gap-1 py-3',
              'min-h-touch transition-colors',
              'focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-primary focus-visible:ring-inset',
              isActive
                ? 'text-primary'
                : 'text-text-secondary active:text-primary',
            ].join(' ')}
            aria-current={isActive ? 'page' : undefined}
            aria-label={tab.label}
          >
            {tab.icon}
            <span
              className={[
                'text-sobre-min font-medium',
                isActive ? 'text-primary' : 'text-text-secondary',
              ].join(' ')}
            >
              {tab.label}
            </span>
            {/* Active indicator bar */}
            {isActive && (
              <span
                className="absolute top-0 inset-x-0 h-0.5 bg-primary rounded-b"
                aria-hidden="true"
              />
            )}
          </button>
        )
      })}
    </nav>
  )
}
